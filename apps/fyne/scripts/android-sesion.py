"""Generate the Android session pins and manifest from the reviewed Play catalog.

No runtime lookup, environment override or upload-key fallback expands trust. The
broker stays disabled until real Binder/Keystore validation is recorded and the
catalog is explicitly reviewed to enable it.

Sytue Office, la edición local (`--edicion local`, empaquetar.sh con
SYTUE_ARBOL=cmd-local), no tiene sesión que compartir (PLAN-EDICION-LOCAL §7.2): su
SesionFirmas sale apagado y SIN ningún paquete de confianza, sin leer el catálogo de la
conectada ni sus `cmd/*/FyneApp.toml` (un árbol autónomo de la edición no los lleva). Las
clases de la sesión van igual en su dex, porque Go pregunta por JNI si está habilitada
(`sistema.SesionAndroidHabilitada`), y dicen que no; el manifiesto no declara broker.
"""
import argparse
import json
from pathlib import Path
import re
import tomllib

FYNE = Path(__file__).resolve().parents[1]
CATALOG = FYNE / "android/session-signers.json"


def catalog(path=CATALOG):
    data = json.loads(Path(path).read_text())
    if data.get("protocol_version") != 1 or type(data.get("runtime_enabled")) is not bool:
        raise ValueError("invalid broker protocol or activation flag")
    expected = set()
    for source in (FYNE / "cmd").glob("*/FyneApp.toml"):
        appid = tomllib.loads(source.read_text())["Details"]["ID"]
        if re.fullmatch(r"eu\.sytue\.[a-z]+", appid):
            expected.add(appid)
    items = {}
    for app in data["apps"]:
        appid = app["package_name"]
        pins = app["certificate_sha256"]
        if appid in items or appid not in expected or not isinstance(pins, list) or not 1 <= len(pins) <= 8:
            raise ValueError("invalid, unknown or duplicate package")
        if any(not isinstance(pin, str) or not re.fullmatch(r"[a-f0-9]{64}", pin) for pin in pins):
            raise ValueError("invalid SHA256 certificate")
        if len(set(pins)) != len(pins):
            raise ValueError("duplicate certificate")
        items[appid] = sorted(pins)
    if set(items) != expected or len(expected) != 15:
        raise ValueError("the reviewed catalog must contain exactly the fifteen products")
    return data["runtime_enabled"], dict(sorted(items.items()))


def products(items, metadata=FYNE / "cmd", product_catalog=FYNE.parent / "nucleo/storage/products.txt"):
    expected = Path(product_catalog).read_text().split()
    if len(expected) != 15 or len(set(expected)) != len(expected) or any(not re.fullmatch(r"[a-z]+", item) for item in expected):
        raise ValueError("invalid private storage product catalog")
    result = {}
    packages = set()
    for source in Path(metadata).glob("*/FyneApp.toml"):
        app = tomllib.loads(source.read_text())
        appid = app["Details"]["ID"]
        if not re.fullmatch(r"eu\.sytue\.[a-z]+", appid):
            continue
        scheme = app["Development"]["esquema"]
        if not re.fullmatch(r"sytue-[a-z]+", scheme):
            raise ValueError("invalid canonical native URL scheme")
        native = scheme.removeprefix("sytue-")
        product = "hub" if native == "one" else native
        if appid not in items or appid in packages or product not in expected or product in result:
            raise ValueError("native metadata is missing, duplicated or inconsistent with the product catalog")
        result[product] = appid
        packages.add(appid)
    if set(result) != set(expected) or packages != set(items):
        raise ValueError("canonical metadata must cover exactly the fifteen private products and signed apps")
    return dict(sorted(result.items()))


EDICIONES = ("conectada", "local")


def java(enabled, items, product_apps=None, edicion="conectada"):
    if edicion == "local":
        # Sin sesión: ni broker ni ningún paquete en quien confiar, sea cual sea el catálogo.
        if enabled or items or product_apps:
            raise ValueError("Sytue Office has no shared session: no broker, no trusted package")
        enabled, items, product_apps = False, {}, {}
        origen = "for Sytue Office, which shares no session (no broker, no trusted package)."
    elif edicion == "conectada":
        product_apps = products(items) if product_apps is None else product_apps
        origen = "from the reviewed final Play certificates."
    else:
        raise ValueError("unknown edition")
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by android-sesion.py " + origen,
        "package eu.sytue.nativo;",
        "import java.util.Arrays;",
        "import java.util.Collections;",
        "import java.util.LinkedHashMap;",
        "import java.util.LinkedHashSet;",
        "import java.util.Map;",
        "import java.util.Set;",
        "final class SesionFirmas {",
        "    static final boolean HABILITADO = " + str(enabled).lower() + ";",
        "    static final Map<String, Set<String>> PAQUETES;",
        "    static final Map<String, String> PRODUCTOS;",
        "    static {",
        "        Map<String, Set<String>> pins = new LinkedHashMap<>();",
    ]
    for appid, pins in items.items():
        values = ", ".join(json.dumps(pin) for pin in pins)
        lines.append(f"        pins.put({json.dumps(appid)}, Collections.unmodifiableSet(new LinkedHashSet<>(Arrays.asList({values}))));")
    lines += ["        PAQUETES = Collections.unmodifiableMap(pins);", "        Map<String, String> products = new LinkedHashMap<>();"]
    for product, appid in product_apps.items():
        lines.append(f"        products.put({json.dumps(product)}, {json.dumps(appid)});")
    lines += ["        PRODUCTOS = Collections.unmodifiableMap(products);", "    }", "    private SesionFirmas() {}", "}"]
    return "\n".join(lines) + "\n"


def manifest(items, section, appid):
    if appid not in items:
        raise ValueError("the demo and unknown products cannot declare a session broker")
    if section == "queries":
        return "\t<queries>\n" + "".join(f'\t\t<package android:name="{item}" />\n' for item in items) + "\t</queries>"
    return f'''\t<provider android:name="eu.sytue.nativo.SesionProveedor"
        android:authorities="{appid}.sytue.sesion"
        android:exported="true" android:grantUriPermissions="false">
        <meta-data android:name="eu.sytue.sesion.PROTOCOLO" android:value="1" />
    </provider>
    <activity android:name="eu.sytue.nativo.SesionDesbloqueo"
        android:exported="false" android:excludeFromRecents="true"
        android:theme="@android:style/Theme.Material.Light.Dialog.NoActionBar" />'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("operation", choices=["java", "queries", "components"])
    parser.add_argument("destination")
    parser.add_argument("--package")
    parser.add_argument("--catalog", default=str(CATALOG))
    parser.add_argument("--edicion", choices=EDICIONES, default="conectada")
    args = parser.parse_args()
    if args.edicion == "local":
        # Ni catálogo ni metadatos de la conectada, y nada que declarar en el manifiesto.
        if args.operation != "java":
            parser.error("Sytue Office declares no session broker: only `java`")
        result = java(False, {}, edicion="local")
    else:
        enabled, items = catalog(args.catalog)
        result = java(enabled, items) if args.operation == "java" else manifest(items, args.operation, args.package)
    if args.destination == "-":
        print(result)
    else:
        destination = Path(args.destination)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(result)


if __name__ == "__main__":
    main()
