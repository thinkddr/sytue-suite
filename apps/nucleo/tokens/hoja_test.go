// fuenteGenerada es paletas_generadas.go tal como sale de LEER las hojas embebidas.
func fuenteGenerada(t *testing.T) []byte {
	t.Helper()
	var crudas [len(pedidosGenerados)][variantes]map[string]uint32
	for i, p := range pedidosGenerados {
		j := mustJuego(p, coloresCSS, aparienciaCSS)
		for v := range variantes {
			crudas[i][v] = map[string]uint32{}
			for n, c := range j.crudas[v] {
				crudas[i][v][n] = uint32(c.R)<<24 | uint32(c.G)<<16 | uint32(c.B)<<8 | uint32(c.A)
			}
		}
	}
	nombres := slices.Sorted(func(yield func(string) bool) {
		for n := range crudas[0][0] {
			if !yield(n) {
				return
			}
		}
	})
	for i := range crudas {
		for v := range crudas[i] {
			if len(crudas[i][v]) != len(nombres) {
				t.Fatalf("el juego %+v en la variante %d tiene %d tokens y el de la casa en claro %d: "+
					"tokenGenerado supone los mismos en todos", pedidosGenerados[i], v, len(crudas[i][v]), len(nombres))
			}
		}
	}
	colores := Colores()

	var b bytes.Buffer
	b.WriteString("// Code generated by `go generate ./tokens`; DO NOT EDIT.\n\n")
	b.WriteString("// Las crudas de los juegos de arranque, leídas de colors.css y appearance.css por\n")
	b.WriteString("// parseCrudasDe (ver hoja.go). Cada token: casa claro, oscuro, traslúcido; papel claro,\n")
	b.WriteString("// oscuro, traslúcido, como 0xRRGGBBAA.\n\n")
	b.WriteString("package tokens\n\n")
	fmt.Fprintf(&b, "const huellaGenerada uint64 = %#016x\n\n", huellaHojas())
	fmt.Fprintf(&b, "var coloresGenerados = %#v\n\n", colores)
	b.WriteString("var tokensGenerados = [...]tokenGenerado{\n")
	for _, n := range nombres {
		fmt.Fprintf(&b, "\t{%q, [len(pedidosGenerados)][variantes]uint32{", n)
		for i := range crudas {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString("{")
			for v := range variantes {
				if v > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%#08x", crudas[i][v][n])
			}
			b.WriteString("}")
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	fuente, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return fuente
}

// TestLasPaletasGeneradasSonLasDeLaHoja: paletas_generadas.go es, byte a byte, lo que sale
// de leer las hojas embebidas, y lo que se carga de él es lo mismo que leerlas. Con
// `-generar` (es lo que corre `go generate ./tokens`) lo reescribe.
//
// VISTO EN ROJO (2026-11-24): con `--sytue-avatar-1` cambiado a mano en colors.css y sin
// regenerar, falla aquí; la huella ya no coincide, así que el paquete lee la hoja.
func TestLasPaletasGeneradasSonLasDeLaHoja(t *testing.T) {
	fuente := fuenteGenerada(t)
	if *generar {
		if err := os.WriteFile("paletas_generadas.go", fuente, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	actual, err := os.ReadFile("paletas_generadas.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(actual, fuente) || huellaGenerada != huellaHojas() {
		t.Fatal("paletas_generadas.go no es lo que sale de las hojas embebidas: `go generate ./tokens`")
	}

	generados, jg := leerHojaCon(true, true)
	leidos, jl := leerHojaCon(false, true)
	if !reflect.DeepEqual(generados, leidos) {
		t.Errorf("los colores de la suite generados son %v y la hoja declara %v", generados, leidos)
	}
	for _, p := range pedidosGenerados {
		quiero := jl[p]
		if quiero == nil {
			quiero = mustJuego(p, coloresCSS, aparienciaCSS)
		}
		if got := jg[p]; got == nil || !reflect.DeepEqual(*got, *quiero) {
			t.Errorf("el juego generado %+v no es el que sale de leer la hoja", p)
		}
	}
}

// TestElArranqueNoLeeLaHoja: con lo generado al día, el juego del papel sale de lo
// generado sin leer la hoja, y el de la casa no se resuelve si se elige el papel antes
// del primer color; y las formas son las generadas, sin leer theme.css.
//
// VISTO EN ROJO con los dos juegos generados pasados a mapas en el `init`: el de la casa
// ya estaba resuelto antes de elegir nada.
func TestElArranqueNoLeeLaHoja(t *testing.T) {
	if !generadasAlDia() {
		t.Skip("lo generado no es de estas hojas: lo dice TestLasPaletasGeneradasSonLasDeLaHoja")
	}
	// El estado del arranque: nada resuelto ni en vigor.
	eleccion.Lock()
	antes, vigor := juegos, enVigor.Load()
	juegos = map[pedido]*juego{}
	enVigor.Store(nil)
	eleccion.Unlock()
	t.Cleanup(func() {
		eleccion.Lock()
		juegos = antes
		enVigor.Store(vigor)
		eleccion.Unlock()
		ElegirCromo("")
	})
	if !ElegirCromo(CromoPapel) {
		t.Error("elegir el papel antes del primer color no dice que cambia")
	}
	eleccion.Lock()
	resueltos := len(juegos)
	eleccion.Unlock()
	if resueltos != 0 {
		t.Errorf("elegir el cromo ha resuelto %d juegos antes del primer color", resueltos)
	}
	lecturas := lecturasDeHoja.Load()
	_ = Color("bg", Light)
	eleccion.Lock()
	_, papel := juegos[pedido{papel: true}]
	_, deLaCasa := juegos[pedido{}]
	eleccion.Unlock()
	if !papel || deLaCasa {
		t.Errorf("el primer color resuelve el papel (%v) y la casa (%v): solo tenía que ser el papel", papel, deLaCasa)
	}
	if lecturasDeHoja.Load() != lecturas {
		t.Error("el juego del papel se ha leído de la hoja y no de lo generado")
	}
	if huellaFormasGenerada != huellaFormas() {
		t.Skip("las formas generadas no son de estas hojas: lo dice TestLasFormasGeneradasSonLasDeLaHoja")
	}
	for i := range formas {
		if reflect.ValueOf(formas[i]).UnsafePointer() != reflect.ValueOf(formasGeneradas[i]).UnsafePointer() {
			t.Errorf("las medidas de la forma %d se han leído de la hoja al arrancar", i)
		}
	}
}

// fuenteFormas es formas_generadas.go tal como sale de LEER las hojas embebidas.
func fuenteFormas(t *testing.T) []byte {
	t.Helper()
	leidas := mustFormas(temaCSS, aparienciaCSS)
	var b bytes.Buffer
	b.WriteString("// Code generated by `go generate ./tokens`; DO NOT EDIT.\n\n")
	b.WriteString("// Las medidas de las dos formas, [0] Marco y [1] Carril, leídas de theme.css y\n")
	b.WriteString("// appearance.css por mustFormas (ver forma.go y hoja.go).\n\n")
	b.WriteString("package tokens\n\n")
	fmt.Fprintf(&b, "const huellaFormasGenerada uint64 = %#016x\n\n", huellaFormas())
	b.WriteString("var formasGeneradas = [2]map[string]Medida{\n")
	for _, f := range leidas {
		b.WriteString("\t{\n")
		for _, n := range slices.Sorted(func(yield func(string) bool) {
			for n := range f {
				if !yield(n) {
					return
				}
			}
		}) {
			fmt.Fprintf(&b, "\t\t%q: {%s, %q},\n", n, strconv.FormatFloat(f[n].Valor, 'g', -1, 64), f[n].Unidad)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	fuente, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return fuente
}

// TestLasFormasGeneradasSonLasDeLaHoja: formas_generadas.go es, byte a byte, lo que sale
