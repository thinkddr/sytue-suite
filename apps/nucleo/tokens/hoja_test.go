// TestLaHuellaCambiaConCadaHoja: un byte de cualquiera de las hojas, o pasar un trozo de
// una a la siguiente, cambia la huella. Es lo único que impide arrancar con lo generado
// de una hoja vieja.
func TestLaHuellaCambiaConCadaHoja(t *testing.T) {
	base := huella(temaCSS, aparienciaCSS)
	for i, hojas := range [][]string{
		{temaCSS + " ", aparienciaCSS},
		{temaCSS, aparienciaCSS[:len(aparienciaCSS)-1]},
		{temaCSS[:100], temaCSS[100:] + aparienciaCSS},
		{temaCSS[:5000] + "x" + temaCSS[5001:], aparienciaCSS},
		{aparienciaCSS, temaCSS},
	} {
		if huella(hojas...) == base {
			t.Errorf("caso %d: la huella no cambia", i)
		}
	}
	if huella(temaCSS, aparienciaCSS) != base {
		t.Error("la huella de las mismas hojas no es la misma")
	}
}
