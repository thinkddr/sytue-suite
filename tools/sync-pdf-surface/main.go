// Command sync-pdf-surface retains backend aliases for the shared PDF engines.
// Run from the repository root after changing the shared public declarations.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type surface struct{ source, pkg, shared, destination string }

func main() {
	surfaces := []surface{
		{"apps/nucleo/pdf", "domain", "pdf", "services/docs/internal/domain/pdf_shared.go"},
		{"apps/nucleo/pdf", "model", "pdf", "apps/nucleo/office/model/pdf_shared.go"},
		{"apps/nucleo/office/model", "domain", "office/model", "services/docs/internal/domain/office_shared.go"},
		{"apps/nucleo/cms", "cms", "cms", "platform/pkg/cms/cms.go"},
		{"apps/nucleo/pdffuente", "pdffuente", "pdffuente", "platform/pkg/pdffuente/pdffuente.go"},
		{"apps/nucleo/pdfsimple", "pdfsimple", "pdfsimple", "platform/pkg/pdfsimple/pdfsimple.go"},
		{"apps/nucleo/pdfdoc", "pdfdoc", "pdfdoc", "platform/pkg/pdfdoc/pdfdoc.go"},
		{"apps/nucleo/pdfdoc/uacheck", "uacheck", "pdfdoc/uacheck", "platform/pkg/pdfdoc/uacheck/shared.go"},
		{"apps/nucleo/guiones", "guiones", "guiones", "platform/pkg/guiones/guiones.go"},
		{"apps/nucleo/clave", "clave", "clave", "platform/pkg/clave/clave.go"},
	}
	for _, s := range surfaces {
		if err := generate(s); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func exportedNames(directory string, exclude ...string) (map[string]string, error) {
	entries, err := os.ReadDir(directory)
	if err != nil {
		return nil, err
	}
	names := map[string]string{}
	for _, entry := range entries {
		omitted := false
		for _, name := range exclude {
			if entry.Name() == name {
				omitted = true
				break
			}
		}
		if omitted {
			continue
		}
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(directory, entry.Name()), nil, 0)
		if err != nil {
			return nil, err
		}
		addDeclarations(names, file)
	}
	return names, nil
}

func addDeclarations(names map[string]string, file *ast.File) {
	for _, declaration := range file.Decls {
		switch d := declaration.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil && d.Name.IsExported() {
				names[d.Name.Name] = "var"
			}
		case *ast.GenDecl:
			for _, raw := range d.Specs {
				addSpecification(names, d.Tok, raw)
			}
		}
	}
}

func addSpecification(names map[string]string, kind token.Token, spec ast.Spec) {
	switch s := spec.(type) {
	case *ast.TypeSpec:
		if s.Name.IsExported() {
			names[s.Name.Name] = "type"
		}
	case *ast.ValueSpec:
		for _, name := range s.Names {
			if name.IsExported() {
				names[name.Name] = kind.String()
			}
		}
	}
}

func render(s surface, names map[string]string) ([]byte, error) {
	ordered := make([]string, 0, len(names))
	for name := range names {
		ordered = append(ordered, name)
	}
	sort.Strings(ordered)
	var out bytes.Buffer
	fmt.Fprint(&out, "// SPDX-License-Identifier: Apache-2.0\n// Copyright (c) 2026 Daniel Delgado Ramos\n// Code generated by tools/sync-pdf-surface. DO NOT EDIT.\n\n")
	fmt.Fprint(&out, "// The implementation is shared with authorized devices. This compatibility\n// surface retains the backend API without a second parser, renderer or signer.\n")
	fmt.Fprintf(&out, "package %s\n\nimport shared %q\n\n", s.pkg, "git.sytue.eu/sytue/one/apps/nucleo/"+s.shared)
	for _, name := range ordered {
		fmt.Fprintf(&out, "%s %s = shared.%s\n", names[name], name, name)
	}
	return format.Source(out.Bytes())
}

func generate(s surface) error {
	var ignored []string
	if s.shared == "office/model" {
		ignored = []string{"pdf_shared.go"}
	}
	names, err := exportedNames(s.source, ignored...)
	if err != nil {
		return err
	}
	data, err := render(s, names)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(s.destination), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(s.destination, data, 0o600); err != nil {
		return err
	}
	fmt.Println("BRIDGE", s.destination, "EXPORTED_SYMBOLS", len(names))
	return nil
}
